import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import ts from 'typescript';

// Documentation tooling only: never import the backend, load .env, or open a DB.
const require = createRequire(import.meta.url);
const yaml = require('js-yaml'); // Already provided by the existing ESLint dependency tree.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const write = (p, value) => fs.writeFileSync(path.join(root, p), value, 'utf8');
const entry = read('backend/src/index.ts');
const ast = ts.createSourceFile('index.ts', entry, ts.ScriptTarget.Latest, true);
let initializer;
function visit(node) {
  if (ts.isVariableDeclaration(node) && node.name.getText(ast) === 'openApiSpec') initializer = node.initializer;
  ts.forEachChild(node, visit);
}
visit(ast);
assert(initializer, 'Embedded openApiSpec initializer was not found');
const expression = ts.transpileModule(`const snapshot = ${initializer.getText(ast)}; snapshot;`, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.None },
}).outputText;
const embedded = JSON.parse(JSON.stringify(vm.runInNewContext(expression, { env: { BACKEND_PORT: 3001 } }, { timeout: 1000 })));
const expected = { ...embedded, servers: [{ url: '/' }] };

const methods = new Set(['get', 'post', 'put', 'patch', 'delete', 'head', 'options']);
const documented = new Set();
for (const [url, item] of Object.entries(embedded.paths)) {
  for (const method of Object.keys(item)) if (methods.has(method)) documented.add(`${method.toUpperCase()} ${url}`);
}
const implemented = new Map();
const recordRoutes = (source, router, prefix, file) => {
  const routePattern = new RegExp(`\\b${router}\\.(get|post|put|patch|delete|head|options)\\(\\s*["']([^"']+)["']`, 'g');
  for (const match of source.matchAll(routePattern)) {
    if (match[2].includes('*')) continue;
    const url = (prefix + (match[2] === '/' ? '' : match[2])).replace(/:([A-Za-z0-9_]+)/g, '{$1}');
    implemented.set(`${match[1].toUpperCase()} ${url}`, file);
  }
};
recordRoutes(entry, 'app', '', 'backend/src/index.ts');
for (const mount of entry.matchAll(/app\.use\("([^"]+)",\s*(\w+Router)\)/g)) {
  const imported = [...entry.matchAll(/import\s*\{\s*(\w+Router)\s*\}\s*from\s*"\.\/routes\/([^".]+)\.js"/g)].find((m) => m[1] === mount[2]);
  assert(imported, `Missing router import for ${mount[2]}`);
  const file = `backend/src/routes/${imported[2]}.ts`;
  recordRoutes(read(file), mount[2], mount[1], file);
}
const missing = [...implemented.keys()].filter((key) => !documented.has(key)).sort();
const unmatched = [...documented].filter((key) => !implemented.has(key)).sort();
const coverage = `# API Coverage\n\nGenerated by \`node scripts/docs/check-docs.mjs --write-api\`.\n\nThis is a static inventory of literal Express route registrations. It does not validate payloads, role checks, middleware behavior, dynamically registered routes, or runtime responses. Wildcard OPTIONS/CORS and the Swagger UI middleware mount are excluded.\n\nThe OpenAPI baseline preserves the embedded contract rather than inventing schemas for uncovered operations. Missing descriptions are tracked as Q-01 in [open questions](open-questions-and-challenges.md). A passing parity check does not mean full API coverage.\n\n- Implemented operations found: **${implemented.size}**\n- Documented operations: **${documented.size}**\n- Implemented operations absent from the contract: **${missing.length}**\n- Contract operations without a matching literal route: **${unmatched.length}**\n\n## Implemented operations missing from OpenAPI\n\n${missing.length ? '| Operation | Source |\n| --- | --- |\n' + missing.map((key) => `| \`${key}\` | \`${implemented.get(key)}\` |`).join('\n') : 'None found.'}\n\n## Contract operations needing route reconciliation\n\n${unmatched.length ? unmatched.map((key) => `- \`${key}\``).join('\n') : 'None found.'}\n\n## Maintenance\n\nUpdate the canonical contract and embedded runtime definition together after reviewing the route. Refresh this report, run the checker, and record request/response and authorization tests in D1. Static counts alone do not close Q-01.\n`;

if (process.argv.includes('--write-api')) {
  write('docs/openapi.yaml', '# Versioned contract baseline; see api-coverage.md for known gaps.\n# Exported from the embedded runtime definition; server URL normalized to same origin.\n' + yaml.dump(expected, { noRefs: true, lineWidth: 110, quotingType: '"' }));
  write('docs/api-coverage.md', coverage);
  console.log(`Exported OpenAPI and coverage: ${documented.size} documented / ${implemented.size} literal route operations.`);
  process.exit(0);
}

const mandatory = ['project-plan.md', 'product-principles.md', 'functional-specification.md', 'technical-implementation-plan.md', 'openapi.yaml', 'database-schema-specification.md', 'implementation-roadmap.md', 'open-questions-and-challenges.md'];
for (const name of mandatory) assert(fs.existsSync(path.join(root, 'docs', name)), `Missing mandatory document: ${name}`);
const spec = yaml.load(read('docs/openapi.yaml'));
assert.deepEqual(spec, expected, 'OpenAPI differs from embedded definition (apart from normalized servers)');
assert.equal(read('docs/api-coverage.md'), coverage, 'API coverage report is stale');
let references = 0;
function checkRefs(value) {
  if (!value || typeof value !== 'object') return;
  if (typeof value.$ref === 'string') {
    assert(value.$ref.startsWith('#/'), `External reference requires explicit validation: ${value.$ref}`);
    let target = spec;
    for (const segment of value.$ref.slice(2).split('/')) target = target?.[segment.replace(/~1/g, '/').replace(/~0/g, '~')];
    assert(target !== undefined, `Unresolved reference: ${value.$ref}`);
    references++;
  }
  Object.values(value).forEach(checkRefs);
}
checkRefs(spec);
for (const [url, item] of Object.entries(spec.paths)) {
  assert(url.startsWith('/'), `Invalid API path: ${url}`);
  for (const [method, operation] of Object.entries(item)) {
    if (!methods.has(method)) continue;
    assert(operation.responses && Object.keys(operation.responses).length, `Missing responses: ${method} ${url}`);
    const parameters = [...(item.parameters ?? []), ...(operation.parameters ?? [])];
    for (const match of url.matchAll(/\{([^}]+)\}/g)) {
      assert(parameters.some((p) => p.name === match[1] && p.in === 'path' && p.required === true), `Missing required path parameter: ${method} ${url} ${match[1]}`);
    }
  }
}

const legacy = new Set(['implementation-plan.md', 'PM-Task-Enhancement-Plan.md', 'PM-Task-Enhance-DeltaPlan.md', 'cm-implementation-plan.md', 'cm-mobile-plan.md', 'mobile_apps_developmentplan.md', 'PM-workflow-mobile-plan.md', 'implement-ngrok.md', 'push_channel.md', 'journal.md']);
for (const name of legacy) assert(read(`docs/${name}`).startsWith('> Historical reference'), `Missing historical banner: ${name}`);
const active = ['README.md', ...fs.readdirSync(path.join(root, 'docs')).filter((name) => name.endsWith('.md') && !legacy.has(name)).map((name) => `docs/${name}`)];
if (fs.existsSync(path.join(root, 'mobile/pm-tech/README.md'))) active.push('mobile/pm-tech/README.md');
let links = 0;
for (const file of active) {
  const body = read(file);
  assert(!/[\x00-\x08\x0b\x0c\x0e-\x1f]/.test(body), `Control character in ${file}`);
  assert(!body.includes('REPLACE_WITH_PROJECT_ID'), `Unresolved project placeholder in ${file}`);
  for (const match of body.matchAll(/\[[^\]\n]+\]\(([^)\n]+)\)/g)) {
    const href = match[1].replace(/^<|>$/g, '').split('#')[0];
    if (!href || /^[a-z]+:/i.test(href)) continue;
    assert(fs.existsSync(path.resolve(root, path.dirname(file), decodeURIComponent(href))), `Broken local link in ${file}: ${href}`);
    links++;
  }
}
const roadmap = read('docs/implementation-roadmap.md');
for (const phase of roadmap.split(/^## D\d+ — /m).slice(1)) {
  for (const section of ['Objective', 'Source documents', 'Checklist', 'Output', 'Challenge / verification']) assert(phase.includes(`### ${section}`), `Phase lacks ${section}`);
}
const schemaTables = [...read('db/schema.sql').matchAll(/CREATE TABLE pm\.(\w+)/g)].map((m) => m[1]);
const schemaDoc = read('docs/database-schema-specification.md');
for (const name of schemaTables) assert(schemaDoc.includes('`' + name + '`'), `Undocumented table: ${name}`);
console.log(`PASS: ${mandatory.length} mandatory documents; ${active.length} active Markdown files; ${links} local links; ${legacy.size} historical banners; D0-D3 phase sections.`);
console.log(`PASS: embedded OpenAPI parity; ${references} local references; required path parameters/responses; current coverage report.`);
console.log(`PASS: ${schemaTables.length} SQL CREATE TABLE entries accounted for in the schema specification.`);
console.log(`LIMIT: ${missing.length} literal route operations lack OpenAPI coverage; ${unmatched.length} documented operations need route reconciliation. Runtime, DB, device, and external-service tests were not run.`);
